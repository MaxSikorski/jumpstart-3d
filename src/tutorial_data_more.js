// small helpers for the checks
const bx = (t, b) => t.box(b.id);
const sz = (t, b) => (t.box(b.id) || {}).size || { x: 0, y: 0, z: 0 };
const groupWith = (t, fn) => t.groups().some(fn);
const deepGroups = (t) => t.groups().filter((g) => (g.node.children || []).some((c) => c.node.t === "group"));
const sketchRegular = (t, n, r) => t.sketches().some((s) => {
  const P = new Map(s.pts.map((q) => [q.id, q]));
  const ls = s.ents.filter((e) => e.t === "line" && !e.proj && !e.construction);
  if (ls.length < n) return false;
  const pts = new Set(); for (const e of ls) { pts.add(e.a); pts.add(e.b); }
  const q = [...pts].map((id) => P.get(id)).filter(Boolean);
  const cx = q.reduce((a, p) => a + p.x, 0) / q.length, cy = q.reduce((a, p) => a + p.y, 0) / q.length;
  return q.length === n && q.every((p) => Math.abs(Math.hypot(p.x - cx, p.y - cy) - r) < 0.6);
});
