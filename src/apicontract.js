export function describe(appVersion) {
  return { apiVersion: API_VERSION, version: API_COMPAT, appVersion, calls: CALLS.map(c => ({ ...c })).sort((a, b) => a.name.localeCompare(b.name)), properties: PROPERTIES.map(p => ({ ...p })).sort((a, b) => a.name.localeCompare(b.name)) };
}
