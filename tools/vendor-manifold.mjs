#!/usr/bin/env node
// Vendors the manifold-3d package into third_party/manifold-3d/.
//
//   node tools/vendor-manifold.mjs <folder of the unpacked manifold-3d package> [--check]
//
// Copies manifold.js (byte for byte) and LICENSE, and writes wasm.js: `export default "<base64 of manifold.wasm, gzip level 9>"`.
// The same package always gives the same wasm.js (node's zlib at level 9 with no name and no time in the header).
// With --check nothing is written: it says whether the committed files match the package.
// third_party/manifold-3d/README.md says where the package comes from and which version is pinned.

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dest = join(root, "third_party", "manifold-3d");

// Node's gzip header carries an OS byte that depends on the platform; the content is the same, so pin it (255 = unknown).
export function wasmModule(wasm) {
  const gz = gzipSync(wasm, { level: 9 });
  gz[9] = 255;
  return '// generated by tools/vendor-manifold.mjs: manifold-3d manifold.wasm, gzip -9, base64\nexport default "' + gz.toString("base64") + '";\n';
}
export const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), check = args.includes("--check"), dir = args.find((a) => !a.startsWith("--"));
  if (!dir) { console.error("usage: node tools/vendor-manifold.mjs <unpacked manifold-3d package folder> [--check]"); process.exit(2); }
  const pkg = resolve(dir);
  for (const f of ["manifold.js", "manifold.wasm", "LICENSE", "package.json"]) if (!existsSync(join(pkg, f))) { console.error(`${pkg} has no ${f}: is it the unpacked manifold-3d package?`); process.exit(2); }
  const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
  const wasm = readFileSync(join(pkg, "manifold.wasm")), js = readFileSync(join(pkg, "manifold.js")), mod = wasmModule(wasm);
  console.log(`manifold-3d ${version}\n  manifold.wasm sha256 ${sha256(wasm)} (${wasm.length} bytes)\n  manifold.js   sha256 ${sha256(js)} (${js.length} bytes)\n  wasm.js ${mod.length} bytes`);
  if (check) {
    const same = (f, buf) => existsSync(join(dest, f)) && Buffer.compare(readFileSync(join(dest, f)), buf) === 0;
    const bad = [["manifold.js", js], ["wasm.js", Buffer.from(mod)], ["LICENSE", readFileSync(join(pkg, "LICENSE"))]].filter(([f, b]) => !same(f, b)).map(([f]) => f);
    console.log(bad.length ? "DIFFERENT: " + bad.join(", ") : "the committed files match this package");
    process.exit(bad.length ? 1 : 0);
  }
  copyFileSync(join(pkg, "manifold.js"), join(dest, "manifold.js"));
  copyFileSync(join(pkg, "LICENSE"), join(dest, "LICENSE"));
  writeFileSync(join(dest, "wasm.js"), mod);
  console.log("written to " + dest + ". Update the hashes and the version in third_party/manifold-3d/README.md and package.json.");
}
